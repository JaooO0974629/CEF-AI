/**
 * Render an icon as an SVG string.
 *
 * @param {keyof typeof ICONS | string} name
 * @param {object} [options]
 * @param {string} [options.className] extra CSS classes
 * @returns {string}
 */
export function icon(name, { className = '' } = {}) {
  const content = ICONS[name];
  if (!content) {
    return '';
  }
  const classes = className ? `icon ${className}` : 'icon';
  return `<svg class="${classes}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${content}</svg>`;
}

